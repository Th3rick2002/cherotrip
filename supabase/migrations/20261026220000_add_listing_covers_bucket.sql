-- Public bucket for listing cover images managed from the internal CMS.
--
-- Anyone can fetch a cover through its public URL (public bucket), but only
-- admins (public.admin_users, checked by public.is_admin()) can list, upload,
-- replace or delete objects. Signing in alone grants nothing here.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'listing-covers',
  'listing-covers',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Object names are generated by the app: "<folder>/<uuid>.<ext>", where the
-- folder is a listing slug or "general". The pattern keeps paths predictable
-- even if a request skips the app.
create policy "Admins can list listing covers"
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'listing-covers'
    and (select public.is_admin())
  );

create policy "Admins can upload listing covers"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'listing-covers'
    and (select public.is_admin())
    and name ~ '^[a-z0-9]+(-[a-z0-9]+)*/[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.(jpg|png|webp)$'
  );

create policy "Admins can replace listing covers"
  on storage.objects
  for update
  to authenticated
  using (
    bucket_id = 'listing-covers'
    and (select public.is_admin())
  )
  with check (
    bucket_id = 'listing-covers'
    and (select public.is_admin())
  );

create policy "Admins can delete listing covers"
  on storage.objects
  for delete
  to authenticated
  using (
    bucket_id = 'listing-covers'
    and (select public.is_admin())
  );
